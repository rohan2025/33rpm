#!/bin/zsh
# Builds 33rpm.app into ./build. Usage: scripts/build_app.sh [debug|release] [--run]
set -euo pipefail

ROOT="${0:A:h:h}"
CONFIG="${1:-release}"
APP="$ROOT/build/33rpm.app"

# Fingerprint every shipped scene file into the binary, so a release build ignores any file that was swapped
# or edited inside the app, even if the app is re-signed afterwards.
FP="$ROOT/App/Sources/ThirtyThreeRPM/SceneFingerprints.swift"
{
  echo "// Generated by scripts/build_app.sh from Scenes/. Do not edit."
  echo "enum SceneFingerprints {"
  echo "    static let sha256: [String: String] = ["
  (cd "$ROOT/Scenes" && find . -type f ! -path '*/_sources/*' ! -name '*.md' ! -name '.DS_Store' | sed 's|^\./||' | LC_ALL=C sort \
    | while read -r f; do echo "        \"$f\": \"$(shasum -a 256 "$f" | cut -d' ' -f1)\","; done)
  echo "    ]"
  echo "}"
} > "$FP"

cd "$ROOT/App"
swift build -c "$CONFIG"
BIN="$(swift build -c "$CONFIG" --show-bin-path)/ThirtyThreeRPM"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
cp "$BIN" "$APP/Contents/MacOS/33rpm"
cp "$ROOT/Assets/AppIcon.icns" "$APP/Contents/Resources/AppIcon.icns"
[[ -d "$ROOT/Scenes" ]] && rsync -a --exclude "_sources" --exclude "*.md" --exclude ".DS_Store" "$ROOT/Scenes/" "$APP/Contents/Resources/Scenes/"

cat > "$APP/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key>        <string>com.rohanverma.33rpm</string>
    <key>CFBundleName</key>              <string>33rpm</string>
    <key>CFBundleDisplayName</key>       <string>33rpm</string>
    <key>CFBundleExecutable</key>        <string>33rpm</string>
    <key>CFBundlePackageType</key>       <string>APPL</string>
    <key>CFBundleShortVersionString</key><string>1.2.4</string>
    <key>CFBundleVersion</key>           <string>7</string>
    <key>LSMinimumSystemVersion</key>    <string>14.0</string>
    <key>NSHighResolutionCapable</key>   <true/>
    <key>LSUIElement</key>               <true/>
    <key>CFBundleIconFile</key>          <string>AppIcon</string>
</dict>
</plist>
PLIST

# Ad-hoc signature: enough for local use and SMAppService launch-at-login.
codesign --force --sign - "$APP"
echo "Built $APP"

if [[ "${2:-}" == "--run" ]]; then
  pkill -x 33rpm 2>/dev/null || true
  open "$APP"
fi
